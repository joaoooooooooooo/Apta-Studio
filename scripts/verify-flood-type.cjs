const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
require('sucrase/register');
const resolve = Module._resolveFilename;
Module._resolveFilename = function (request, parent, ...rest) {
  return resolve.call(this, request.startsWith('@/') ? path.join(__dirname, '..', request.slice(2)) : request, parent, ...rest);
};

const { floodType } = require('../templates/motion-chips/flood-type');
const { DEFAULT_LOOK, FONT_WEIGHT, SCALE_TABLE, ENTER_TABLE, DURATION, CYCLE_TICKS, ZOOM_START, ESCAPE_START, floodTickAt, hash, sample } = require('../templates/motion-chips/flood-type/params');
const { socialArtwork } = require('../lib/socialRenderer');
const { glyphsFor } = require('../templates/motion-chips/flood-type/draw');
assert.equal(floodType.controls.some(control => control.key === 'style'), false);
assert.equal(FONT_WEIGHT, 600);
assert.equal(floodType.controls.find(control => control.key === 'phrase').default, DEFAULT_LOOK.lines.join(' '));
assert.equal(floodType.controls.find(control => control.key === 'textBoxWidth').default, 100);
assert.equal(floodType.controls.find(control => control.key === 'textBoxWidth').unit, '%');
assert.equal(floodType.controls.find(control => control.key === 'textScale').default, 100);
assert.equal(floodType.controls.find(control => control.key === 'textScale').min, 1);
assert.equal(floodType.controls.find(control => control.key === 'lineHeight').default, 108.4);
assert.equal(floodType.controls.find(control => control.key === 'peakScale').max, 5.2);
assert.equal(floodType.controls.some(control => control.key === 'typeSize'), false);
assert.equal(floodType.controls.some(control => control.key === 'firstLine' || control.key === 'secondLine'), false);
assert.equal(floodType.controls.find(control => control.key === 'backgroundColor').default, DEFAULT_LOOK.bg);
assert.equal(floodType.controls.find(control => control.key === 'textColor').default, DEFAULT_LOOK.ink);
assert.equal(socialArtwork(floodType.meta.id).referenceDuration, DURATION);
assert.equal(sample([.25], .5), .25);
assert.equal(sample(SCALE_TABLE, 0), 0);
assert.equal(sample(SCALE_TABLE, 1), 1);
assert.ok(Math.max(...SCALE_TABLE) > 1 && Math.max(...SCALE_TABLE) < 1.06);
assert.equal(sample(ENTER_TABLE, 1), 1);
assert.equal(hash(5, 2), hash(5, 2));
assert.notEqual(hash(5, 2), hash(5, 3));
const measure = { font: '', letterSpacing: '0px', measureText(value) {
  const px = Number(this.font.match(/([\d.]+)px/)?.[1] ?? 100);
  return { width: value.length * px * .44, actualBoundingBoxLeft: 0, actualBoundingBoxRight: value.length * px * .44, actualBoundingBoxAscent: px * .7, actualBoundingBoxDescent: px * .1 };
} };
const narrow = glyphsFor(measure, 'Full Bleed', 1344, 620, .5, 1, 1.08, -.035, 1);
const wide = glyphsFor(measure, 'Full Bleed', 1344, 620, 1, 1, 1.08, -.035, 1);
assert.equal(narrow.px, wide.px);
assert.ok(new Set(narrow.glyphs.map(g => g.y)).size > 1);
assert.equal(new Set(wide.glyphs.map(g => g.y)).size, 1);
assert.ok(glyphsFor(measure, 'Full Bleed', 1344, 620, 1, .75, 1.08, -.035, 1).px < wide.px);
const loose = glyphsFor(measure, 'Full Bleed', 1344, 620, .5, 1, 1.5, -.035, 1);
assert.ok(Math.max(...loose.glyphs.map(g => g.y)) - Math.min(...loose.glyphs.map(g => g.y)) > Math.max(...narrow.glyphs.map(g => g.y)) - Math.min(...narrow.glyphs.map(g => g.y)));
assert.equal(floodTickAt(.2, DURATION), floodTickAt(.2, DURATION + 8));
assert.equal(floodTickAt(.9, DURATION + 8), 17);
assert.ok(Math.abs(floodTickAt(DURATION + 8 - (CYCLE_TICKS - ESCAPE_START) / 30, DURATION + 8) - ESCAPE_START) < 1e-8);
assert.ok(Math.abs(floodTickAt(DURATION + 8 - (CYCLE_TICKS - ZOOM_START) / 30, DURATION + 8) - ZOOM_START) < 1e-8);
console.log('Flood Type: one editable look, deterministic poses, and export registration passed.');
